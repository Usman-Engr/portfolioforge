"use client";

import { useState, useEffect } from "react";
import {
  X,
  Check,
  Loader2,
  AlertCircle,
  Sparkles,
  Globe,
  Shield,
  Rocket,
} from "lucide-react";
import {
  generateSlug,
  validateSlug,
  isSlugAvailable,
  generateSlugSuggestions,
} from "@/lib/utils/slug";
import { motion, AnimatePresence } from "framer-motion";

interface PublishModalProps {
  isOpen: boolean;
  onClose: () => void;
  onPublish: (slug: string) => Promise<void>;
  currentSlug?: string;
  portfolioName: string;
}

export default function PublishModal({
  isOpen,
  onClose,
  onPublish,
  currentSlug,
  portfolioName,
}: PublishModalProps) {
  const [slug, setSlug] = useState(currentSlug || "");
  const [isChecking, setIsChecking] = useState(false);
  const [isAvailable, setIsAvailable] = useState<boolean | null>(null);
  const [isPublishing, setIsPublishing] = useState(false);
  const [error, setError] = useState("");
  const [suggestions, setSuggestions] = useState<string[]>([]);
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);

  useEffect(() => {
    if (isOpen && !currentSlug && portfolioName && !hasAutoGenerated) {
      const autoSlug = generateSlug(portfolioName);
      setSlug(autoSlug);
      setHasAutoGenerated(true);
    }
  }, [isOpen, currentSlug, portfolioName, hasAutoGenerated]);

  useEffect(() => {
    if (!slug || slug === currentSlug) {
      setIsAvailable(null);
      setError("");
      setSuggestions([]);
      return;
    }

    const checkAvailability = async () => {
      setIsChecking(true);
      setError("");
      setSuggestions([]);

      const validation = validateSlug(slug);
      if (!validation.valid) {
        setError(validation.error || "Invalid slug format");
        setIsAvailable(false);
        setIsChecking(false);
        return;
      }

      try {
        const available = await isSlugAvailable(slug);
        setIsAvailable(available);

        if (!available) {
          setError("This slug is already taken");
          const slugSuggestions = generateSlugSuggestions(slug);
          setSuggestions(slugSuggestions.slice(0, 3));
        }
      } catch (err) {
        setError("Failed to check availability");
        setIsAvailable(false);
      } finally {
        setIsChecking(false);
      }
    };

    const timer = setTimeout(checkAvailability, 500);
    return () => clearTimeout(timer);
  }, [slug, currentSlug]);

  const handlePublish = async () => {
    if (!isAvailable && slug !== currentSlug) {
      setError("Please choose an available slug");
      return;
    }

    setIsPublishing(true);
    setError("");

    try {
      await onPublish(slug);
      onClose();
    } catch (err: any) {
      setError(err.message || "Failed to publish portfolio");
    } finally {
      setIsPublishing(false);
    }
  };

  if (!isOpen) return null;

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-2000 flex items-center justify-center p-4">
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          onClick={onClose}
          className="absolute inset-0 bg-black/90 backdrop-blur-xl"
        />

        <motion.div
          initial={{ opacity: 0, scale: 0.9, y: 20 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.9, y: 20 }}
          className="relative w-full max-w-xl bg-[#0a0a0a] border border-white/10 rounded-[40px] shadow-2xl overflow-hidden"
        >
          {/* Artistic Header */}
          <div className="relative h-40 overflow-hidden bg-white/5 flex items-center justify-center">
            <div className="absolute inset-0 bg-linear-to-br from-blue-600/20 to-purple-600/20" />
            <div className="relative z-10 text-center">
              <div className="w-16 h-16 bg-white text-black rounded-2xl flex items-center justify-center mx-auto mb-4 rotate-3 shadow-2xl">
                <Rocket className="w-8 h-8" />
              </div>
              <h2 className="text-3xl font-black tracking-tighter text-white uppercase italic">
                Ready to Launch?
              </h2>
            </div>
            <button
              onClick={onClose}
              className="absolute top-6 right-6 p-2 bg-black/40 hover:bg-white text-gray-400 hover:text-black rounded-full transition-all"
            >
              <X className="w-5 h-5" />
            </button>
          </div>

          <div className="p-10 space-y-8">
            {/* URL Configuration */}
            <div className="space-y-4">
              <div className="flex items-center justify-between">
                <label className="text-[10px] font-black uppercase tracking-[0.2em] text-gray-500">
                  Project Identity (URL Slug)
                </label>
                {!currentSlug && portfolioName && (
                  <button
                    type="button"
                    onClick={() => setSlug(generateSlug(portfolioName))}
                    className="text-[10px] font-black text-blue-400 hover:text-white uppercase tracking-widest flex items-center gap-2 transition-colors"
                  >
                    <Sparkles className="w-3 h-3" />
                    Auto-Sync
                  </button>
                )}
              </div>

              <div className="relative">
                <span className="absolute left-6 top-1/2 -translate-y-1/2 text-gray-600 font-bold text-sm">
                  /p/
                </span>
                <input
                  type="text"
                  value={slug}
                  onChange={(e) => setSlug(generateSlug(e.target.value))}
                  className={`w-full pl-12 pr-12 py-5 bg-white/5 border rounded-2xl font-bold text-white transition-all outline-hidden ${
                    isAvailable === true
                      ? "border-green-500/50 focus:border-green-500"
                      : isAvailable === false
                      ? "border-red-500/50 focus:border-red-500"
                      : "border-white/10 focus:border-white/30"
                  }`}
                  placeholder="your-unique-slug"
                />
                <div className="absolute right-6 top-1/2 -translate-y-1/2">
                  {isChecking ? (
                    <Loader2 className="w-5 h-5 animate-spin text-blue-500" />
                  ) : isAvailable === true ? (
                    <Check className="w-5 h-5 text-green-500" />
                  ) : (
                    isAvailable === false && (
                      <AlertCircle className="w-5 h-5 text-red-500" />
                    )
                  )}
                </div>
              </div>

              {/* Suggestions */}
              <AnimatePresence>
                {suggestions.length > 0 && !isChecking && (
                  <motion.div
                    initial={{ opacity: 0, y: -10 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="flex flex-wrap gap-2"
                  >
                    <p className="w-full text-[10px] font-black text-gray-600 uppercase tracking-widest mb-1">
                      Available Alternatives:
                    </p>
                    {suggestions.map((suggestion) => (
                      <button
                        key={suggestion}
                        type="button"
                        onClick={() => setSlug(suggestion)}
                        className="px-4 py-1.5 text-[10px] font-black bg-blue-500/10 text-blue-400 border border-blue-500/20 rounded-full hover:bg-blue-500 hover:text-white transition-all uppercase tracking-widest"
                      >
                        {suggestion}
                      </button>
                    ))}
                  </motion.div>
                )}
              </AnimatePresence>
            </div>

            {error && (
              <div className="p-4 bg-red-500/10 border border-red-500/20 rounded-2xl flex items-center gap-3 text-red-500">
                <AlertCircle className="w-5 h-5 shrink-0" />
                <p className="text-xs font-bold uppercase tracking-tight">
                  {error}
                </p>
              </div>
            )}

            <div className="grid grid-cols-2 gap-4">
              <div className="p-4 bg-white/5 border border-white/5 rounded-2xl group hover:border-blue-500/30 transition-all">
                <Globe className="w-5 h-5 text-blue-400 mb-3 group-hover:scale-110 transition-transform" />
                <h4 className="text-[10px] font-black text-white uppercase tracking-widest mb-1">
                  Global Reach
                </h4>
                <p className="text-[10px] text-gray-500 font-bold leading-relaxed">
                  Instantly accessible to anyone, anywhere in the world.
                </p>
              </div>
              <div className="p-4 bg-white/5 border border-white/5 rounded-2xl group hover:border-purple-500/30 transition-all">
                <Shield className="w-5 h-5 text-purple-400 mb-3 group-hover:scale-110 transition-transform" />
                <h4 className="text-[10px] font-black text-white uppercase tracking-widest mb-1">
                  Studio SSL
                </h4>
                <p className="text-[10px] text-gray-500 font-bold leading-relaxed">
                  256-bit encryption secured per deployment.
                </p>
              </div>
            </div>

            <button
              onClick={handlePublish}
              disabled={
                isPublishing || (!isAvailable && slug !== currentSlug) || !slug
              }
              className="w-full py-6 bg-white text-black rounded-[20px] font-black text-sm uppercase tracking-[0.3em] hover:scale-[1.02] active:scale-95 transition-all shadow-2xl disabled:opacity-30 disabled:grayscale flex items-center justify-center gap-4"
            >
              {isPublishing ? (
                <>
                  <Loader2 className="w-6 h-6 animate-spin" />
                  Syncing Assets
                </>
              ) : (
                <>
                  <Rocket className="w-5 h-5" />
                  Launch Site
                </>
              )}
            </button>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
}
